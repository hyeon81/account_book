"""Storage port for confirmed ledger transactions."""
from __future__ import annotations

from typing import Protocol


class TransactionRepository(Protocol):
    def list(self, filters: dict) -> dict: ...
    def create(self, transaction: dict) -> dict: ...
    def update(self, transaction_id: str, changes: dict) -> dict: ...
    def delete(self, transaction_id: str) -> None: ...
    def import_items(self, items: list[dict]) -> dict: ...
